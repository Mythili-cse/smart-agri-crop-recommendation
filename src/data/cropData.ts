/**
 * Fallback crop if lookup fails
 */
export const fallbackCrop: CropDetails = cropDataset[0]; // Rice

/**
 * Dynamic lookup function by ID or Name
 */
export function getCropById(idOrName: string): CropDetails {
  if (!idOrName) return fallbackCrop;
  const clean = idOrName.trim().toLowerCase();
  
  const match = cropDataset.find(
    (c) => c.id.toLowerCase() === clean || c.name.toLowerCase() === clean || c.name.toLowerCase().includes(clean)
  );

  if (match) {
    // Ensure image is retrieved directly from cropImages mapping
    return {
      ...match,
      image: getCropImage(match.id),
    };
  }

  return {
    ...fallbackCrop,
    image: getCropImage(fallbackCrop.id),
  };
}
